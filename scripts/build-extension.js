#!/usr/bin/env node

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const OFFICIAL_PROXY_URL = 'https://draftapply.onrender.com';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = join(ROOT, 'extension-ready');

export function validateProxyUrl(value) {
  let parsed;
  try { parsed = new URL(value); } catch { throw new Error(`Invalid --proxy-url: ${value}`); }
  const loopback = parsed.hostname === 'localhost'
    || parsed.hostname === '127.0.0.1'
    || parsed.hostname === '[::1]';
  if (parsed.protocol !== 'https:' && !(parsed.protocol === 'http:' && loopback)) {
    throw new Error('--proxy-url must use HTTPS (HTTP is allowed only for loopback hosts)');
  }
  if (parsed.username || parsed.password || parsed.search || parsed.hash) {
    throw new Error('--proxy-url must not contain credentials, a query, or a fragment');
  }
  return parsed.href.replace(/\/$/, '');
}

export function buildExtension({ proxyUrl = OFFICIAL_PROXY_URL, outputDir = join(ROOT, 'dist', 'extension') } = {}) {
  const resolvedProxyUrl = validateProxyUrl(proxyUrl);
  const resolvedOutput = resolve(outputDir);
  if (resolvedOutput === SOURCE_DIR || resolvedOutput.startsWith(`${SOURCE_DIR}/`)) {
    throw new Error('Build output must not overwrite extension-ready');
  }
  rmSync(resolvedOutput, { recursive: true, force: true });
  mkdirSync(resolvedOutput, { recursive: true });
  cpSync(SOURCE_DIR, resolvedOutput, { recursive: true });

  const manifestPath = join(resolvedOutput, 'manifest.json');
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const officialPermission = `${new URL(OFFICIAL_PROXY_URL).origin}/*`;
  const proxyPermission = `${new URL(resolvedProxyUrl).origin}/*`;
  const matches = manifest.host_permissions.filter(permission => permission === officialPermission);
  if (matches.length !== 1) throw new Error(`Expected exactly one official proxy host permission, found ${matches.length}`);
  manifest.host_permissions = manifest.host_permissions.map(permission =>
    permission === officialPermission ? proxyPermission : permission);
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(join(resolvedOutput, 'build-config.js'),
    `// Generated by scripts/build-extension.js. Do not edit this generated copy.\nexport const PROXY_URL = ${JSON.stringify(resolvedProxyUrl)};\n`);
  writeFileSync(join(resolvedOutput, 'build-info.json'), `${JSON.stringify({
    proxyUrl: resolvedProxyUrl,
    official: resolvedProxyUrl === OFFICIAL_PROXY_URL,
    extensionVersion: manifest.version,
  }, null, 2)}\n`);
  return { outputDir: resolvedOutput, proxyUrl: resolvedProxyUrl, manifest };
}

function option(name) {
  const prefix = `--${name}=`;
  return process.argv.slice(2).find(arg => arg.startsWith(prefix))?.slice(prefix.length);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = buildExtension({ proxyUrl: option('proxy-url') || OFFICIAL_PROXY_URL, outputDir: option('output') || undefined });
    console.log(`Built extension for ${result.proxyUrl} at ${result.outputDir}`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
